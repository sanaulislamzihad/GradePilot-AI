"""CSV exports and PDF reports.

PDFs are rendered from escaped HTML with PyMuPDF's Story layout engine, so no
extra dependency is needed and student text can never inject markup. CSV cells
that a spreadsheet would treat as formulas are neutralised.
"""

import csv
import html
import io

import pymupdf

from app.schemas.results import ExamAnalytics, ResultView

_CSS = """
* { font-family: sans-serif; color: #18181b; }
body { font-size: 10pt; }
h1 { font-size: 16pt; margin: 0 0 4pt 0; }
h2 { font-size: 12pt; margin: 14pt 0 4pt 0; }
p { margin: 2pt 0; }
.muted { color: #71717a; }
.total { font-size: 14pt; font-weight: bold; }
table { border-collapse: collapse; width: 100%; margin-top: 4pt; }
th { text-align: left; font-size: 9pt; color: #52525b; border-bottom: 1px solid #a1a1aa; padding: 3pt; }
td { border-bottom: 1px solid #e4e4e7; padding: 3pt; vertical-align: top; }
.r { text-align: right; }
.note { border: 1px solid #d4d4d8; padding: 6pt; margin-top: 6pt; }
"""

_FORMULA_PREFIXES = ("=", "+", "-", "@", "\t", "\r")


def _e(value) -> str:
    return html.escape("" if value is None else str(value))


def _marks(value) -> str:
    if value is None:
        return "—"
    number = float(value)
    return str(int(number)) if number.is_integer() else f"{number:.2f}".rstrip("0").rstrip(".")


def _font_css(archive: pymupdf.Archive) -> str:
    """Embed Noto Sans (from pymupdf-fonts) so punctuation and accented names render;
    the built-in PDF fonts only cover basic Latin."""
    try:
        return pymupdf.css_for_pymupdf_font("notos", archive=archive, name="sans-serif")
    except Exception:  # noqa: BLE001 - fall back to the built-in font if the package is missing
        return ""


def _render(body: str) -> bytes:
    buffer = io.BytesIO()
    writer = pymupdf.DocumentWriter(buffer)
    archive = pymupdf.Archive()
    story = pymupdf.Story(html=f"<body>{body}</body>", user_css=_font_css(archive) + _CSS, archive=archive)
    page = pymupdf.paper_rect("a4")
    content = page + (48, 48, -48, -56)
    more = True
    while more:
        device = writer.begin_page(page)
        more, _ = story.place(content)
        story.draw(device)
        writer.end_page()
    writer.close()
    # Keep only the glyphs actually used; the embedded font is otherwise ~1 MB.
    document = pymupdf.open(stream=buffer.getvalue(), filetype="pdf")
    try:
        document.subset_fonts()
    except Exception:  # noqa: BLE001 - subsetting is an optimisation only
        pass
    return document.tobytes(garbage=3, deflate=True)


def result_pdf(view: ResultView) -> bytes:
    status = "Provisional result — subject to teacher review" if view.provisional else (
        f"Published {view.published_at:%d %b %Y}" if view.published_at else "Result"
    )
    course = " · ".join(filter(None, [view.course_code, f"Section {view.section_name}" if view.section_name else None]))
    parts = [
        f"<h1>{_e(view.exam_title)}</h1>",
        f"<p class='muted'>{_e(course)}</p>" if course else "",
        f"<p>{_e(view.student_name)} · Student ID {_e(view.student_number)} · Submission {_e(view.submission_code)}</p>",
        f"<p class='muted'>{_e(status)}</p>",
        f"<p class='total'>{_marks(view.total)} / {_marks(view.max_marks)} ({_marks(view.percentage)}%)</p>",
    ]
    if view.teacher_comment:
        parts.append(f"<div class='note'><b>Teacher's comment</b><p>{_e(view.teacher_comment)}</p></div>")
    for q in view.questions:
        parts.append(f"<h2>Question {_e(q.label)} — {_marks(q.awarded)} / {_marks(q.max_marks)}</h2>")
        parts.append(f"<p class='muted'>{_e(q.text)}</p>")
        if q.criteria:
            rows = "".join(
                f"<tr><td>{_e(c.name)}</td><td class='r'>{_marks(c.awarded)} / {_marks(c.max_marks)}</td>"
                f"<td>{_e(c.explanation)}</td></tr>"
                for c in q.criteria
            )
            parts.append(f"<table><tr><th>Criterion</th><th class='r'>Marks</th><th>Comment</th></tr>{rows}</table>")
        if q.feedback:
            parts.append(f"<p><b>Feedback:</b> {_e(q.feedback)}</p>")
        if q.missing_concepts:
            parts.append(f"<p><b>To improve:</b> {_e('; '.join(q.missing_concepts))}</p>")
        if q.teacher_comment:
            parts.append(f"<p><b>Teacher:</b> {_e(q.teacher_comment)}</p>")
    parts.append("<p class='muted' style='margin-top:14pt'>Generated by GradePilot AI.</p>")
    return _render("".join(parts))


def class_report_pdf(analytics: ExamAnalytics, rows: list[dict]) -> bytes:
    a = analytics
    parts = [
        f"<h1>{_e(a.exam_title)} — class report</h1>",
        f"<p class='muted'>Statistics use teacher-approved marks only ({a.graded_count} of {a.total_submissions} submissions).</p>",
        "<table>",
        f"<tr><td>Students</td><td class='r'>{a.total_students}</td><td>Submissions</td><td class='r'>{a.total_submissions}</td></tr>",
        f"<tr><td>Average</td><td class='r'>{_marks(a.average)} / {_marks(a.total_marks)}</td><td>Median</td><td class='r'>{_marks(a.median)}</td></tr>",
        f"<tr><td>Highest</td><td class='r'>{_marks(a.highest)}</td><td>Lowest</td><td class='r'>{_marks(a.lowest)}</td></tr>",
        f"<tr><td>Pending review</td><td class='r'>{a.pending_evaluations}</td><td>Published</td><td class='r'>{a.published_results}</td></tr>",
        "</table>",
        "<h2>Score distribution</h2><table><tr><th>Range</th><th class='r'>Students</th></tr>",
        *[f"<tr><td>{_e(b.label)}</td><td class='r'>{b.count}</td></tr>" for b in a.distribution],
        "</table>",
        "<h2>Questions</h2><table><tr><th>Question</th><th class='r'>Average</th><th class='r'>Average %</th><th class='r'>Answered</th></tr>",
        *[
            f"<tr><td>{_e(q.label)}</td><td class='r'>{_marks(q.average)} / {_marks(q.max_marks)}</td>"
            f"<td class='r'>{_marks(q.average_percentage)}</td><td class='r'>{q.answered}</td></tr>"
            for q in a.questions
        ],
        "</table>",
    ]
    if a.common_missing_concepts:
        parts.append("<h2>Most common missing concepts</h2><table><tr><th>Concept</th><th class='r'>Times</th></tr>")
        parts.extend(f"<tr><td>{_e(c.concept)}</td><td class='r'>{c.count}</td></tr>" for c in a.common_missing_concepts)
        parts.append("</table>")
    parts.append("<h2>Students</h2><table><tr><th>Student ID</th><th>Name</th><th>Status</th><th class='r'>Marks</th></tr>")
    parts.extend(
        f"<tr><td>{_e(r['student_number'])}</td><td>{_e(r['student_name'])}</td><td>{_e(r['status'])}</td>"
        f"<td class='r'>{_marks(r['final_total'])}</td></tr>"
        for r in rows
    )
    parts.append("</table>")
    return _render("".join(parts))


def safe_cell(value) -> str:
    """Stop spreadsheet apps from running cell text as a formula (CSV injection)."""
    text = "" if value is None else str(value)
    return f"'{text}" if text.startswith(_FORMULA_PREFIXES) else text


def results_csv(header: list[str], rows: list[list]) -> str:
    buffer = io.StringIO()
    writer = csv.writer(buffer)
    writer.writerow([safe_cell(h) for h in header])
    for row in rows:
        writer.writerow([safe_cell(v) for v in row])
    return buffer.getvalue()
